def make_badge(name, icon_key):
    path = ICONS.get(icon_key, '')
    svg = f'<svg class="skill-icon" viewBox="0 0 24 24" width="16" height="16" aria-hidden="true">{path}</svg>'
    return f'<span class="skill-badge">{svg}<span>{name}</span></span>'

def build_grid():
    cards = []
    for cat in CATEGORIES:
        badges = '\n                  '.join(make_badge(name, k) for name, k in cat['skills'])
        card = f'''              <article>
                <h3>{cat['title']}</h3>
                <div class="skill-badges">
                  {badges}
                </div>
                <a href="{cat['link']}">{cat['linkLabel']}</a>
              </article>'''
        cards.append(card)
    return '<div class="skills-grid" aria-label="Technical skills">\n' + '\n'.join(cards) + '\n            </div>'

grid_html = build_grid()

